"""Generates WFSounds.java, sounds.json and subtitle lang entries from tools/audio/sound_spec.py."""
import json, os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "audio"))
import sound_spec as S  # noqa: E402

ASSETS = os.path.join(ROOT, "src/main/resources/assets/worldsfall")
JAVA = os.path.join(ROOT, "src/main/java/dev/worldsfall/registry/WFSounds.java")

def const(eid):
    return re.sub(r"[^A-Z0-9]", "_", eid.upper())

def build():
    events = {}   # id -> dict(sounds=[...], subtitle=key or None, stream=bool)
    lang = {}
    for eid, (sub, files, _n) in S.block_events().items():
        events[eid] = {"sounds": [f"worldsfall:{f}" for f in files], "subtitle": sub}
    for eid, (sub, files, _n) in S.EVENTS.items():
        key = f"subtitles.worldsfall.{eid}"
        lang[key] = sub
        events[eid] = {"sounds": [f"worldsfall:{f}" for f in files], "subtitle": key}
    for biome, (loop, adds, _n) in S.AMBIENT.items():
        events[f"ambient.{biome}.loop"] = {"sounds": [{"name": f"worldsfall:{loop}", "stream": True}], "subtitle": None}
        key = f"subtitles.worldsfall.ambient.{biome}.additions"
        lang[key] = {"chorus_reach": "Glass chimes ring", "stillwater_basins": "Something drips far away",
                     "fallen_spires": "Stone settles", "the_hoard": "A familiar sound, wrong",
                     "the_underside": "A drip falls upward", "the_drift": "A distant call",
                     "fracture_ring": "Shards grind"}[biome]
        events[f"ambient.{biome}.additions"] = {"sounds": [f"worldsfall:{a}" for a in adds], "subtitle": key}
    for eid, (stem, _n) in S.MUSIC.items():
        events[eid] = {"sounds": [{"name": f"worldsfall:{stem}", "stream": True}], "subtitle": None}
    # music disc uses the full Unmade layer 3 + stillness? Disc plays "stillness".
    events["music_disc.unmade"] = {"sounds": [{"name": "worldsfall:music/stillness", "stream": True}], "subtitle": None}
    return events, lang

def main():
    events, lang = build()
    sj = {}
    for eid, e in sorted(events.items()):
        entry = {"sounds": e["sounds"]}
        if e["subtitle"]:
            entry["subtitle"] = e["subtitle"]
        sj[eid] = entry
    os.makedirs(ASSETS, exist_ok=True)
    with open(os.path.join(ASSETS, "sounds.json"), "w") as f:
        json.dump(sj, f, indent=2, sort_keys=True)
    with open(os.path.join(ROOT, "tools/gen/sound_lang.json"), "w") as f:
        json.dump(lang, f, indent=2, sort_keys=True)
    lines = ["// GENERATED by tools/gen/gen_sounds.py — do not edit.",
             "package dev.worldsfall.registry;", "",
             "import dev.worldsfall.Worldsfall;",
             "import net.minecraft.core.Holder;",
             "import net.minecraft.core.registries.Registries;",
             "import net.minecraft.resources.Identifier;",
             "import net.minecraft.sounds.SoundEvent;",
             "import net.neoforged.neoforge.registries.DeferredHolder;",
             "import net.neoforged.neoforge.registries.DeferredRegister;", "",
             "public final class WFSounds {",
             "    public static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(Registries.SOUND_EVENT, Worldsfall.MODID);", ""]
    for eid in sorted(events):
        lines.append(f"    public static final DeferredHolder<SoundEvent, SoundEvent> {const(eid)} = reg(\"{eid}\");")
    lines += ["",
              "    private WFSounds() {}", "",
              "    private static DeferredHolder<SoundEvent, SoundEvent> reg(String id) {",
              "        return SOUNDS.register(id, () -> SoundEvent.createVariableRangeEvent(Identifier.fromNamespaceAndPath(Worldsfall.MODID, id)));",
              "    }", "",
              "    public static Holder<SoundEvent> holder(DeferredHolder<SoundEvent, SoundEvent> h) {",
              "        return h;",
              "    }",
              "}", ""]
    os.makedirs(os.path.dirname(JAVA), exist_ok=True)
    with open(JAVA, "w") as f:
        f.write("\n".join(lines))
    print(f"sound events: {len(events)}")

if __name__ == "__main__":
    main()
